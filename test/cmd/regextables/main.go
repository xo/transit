// Command regextables writes the Unicode tables of the Rust crate regex-syntax
// as the Go package generate/internal/regexsyntax/unicodetables (D59, D60).
//
// The crate holds its tables in the Rust files of src/unicode_tables, which
// ucd-generate made. The command reads each file that mod.rs names, and it
// writes one Go file for each, with the same base name. It keeps the order of
// every entry, because the port of unicode.rs does a binary search on some
// tables. It copies LICENSE-UNICODE with the tables. It fails on any Rust form
// that it does not know.
//
// Run it from the test module:
//
//	cd test && go run ./cmd/regextables
//
// It needs the source of the crate on disk. Cargo keeps it in
// $CARGO_HOME/registry/src, or in ~/.cargo/registry/src, after a build of
// upstream tree-sitter.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// crateVersion is the version of regex-syntax that upstream pins at the base
// commit (D59).
const crateVersion = "0.8.11"

// generatedPrefix starts each Go file that the command writes.
const generatedPrefix = "// Code generated by test/cmd/regextables "

// licenseFile is the license of the Unicode data, which the command copies.
const licenseFile = "LICENSE-UNICODE"

func main() {
	os.Exit(mainCode())
}

// mainCode runs the command and returns the exit code.
func mainCode() int {
	version := flag.String("version", crateVersion, "the version of regex-syntax")
	src := flag.String("src", "", "the folder src/unicode_tables of regex-syntax (default: the crate of that version under $CARGO_HOME/registry/src)")
	out := flag.String("out", "", "the folder to write the Go package to (default: generate/internal/regexsyntax/unicodetables of the repository)")
	flag.Parse()
	if err := run(os.Stdout, *src, *out, *version); err != nil {
		fmt.Fprintln(os.Stderr, "regextables:", err)
		return 1
	}
	return 0
}

// run finds the folders that the flags leave empty, converts the tables, and
// writes its progress to w.
func run(w io.Writer, src, out, version string) error {
	if src == "" {
		var err error
		if src, err = findSource(version); err != nil {
			return err
		}
	}
	if out == "" {
		root, err := repoRoot()
		if err != nil {
			return err
		}
		out = filepath.Join(root, "generate", "internal", "regexsyntax", "unicodetables")
	}
	if err := checkCrateVersion(src, version); err != nil {
		return err
	}
	return convert(w, src, out, version)
}

// findSource returns the folder src/unicode_tables of the crate regex-syntax at
// a version, in the registry of cargo.
func findSource(version string) (string, error) {
	home := os.Getenv("CARGO_HOME")
	if home == "" {
		user, err := os.UserHomeDir()
		if err != nil {
			return "", fmt.Errorf("finding the home folder: %w", err)
		}
		home = filepath.Join(user, ".cargo")
	}
	pattern := filepath.Join(home, "registry", "src", "*", "regex-syntax-"+version, "src", "unicode_tables")
	matches, err := filepath.Glob(pattern)
	if err != nil {
		return "", fmt.Errorf("finding the crate with %s: %w", pattern, err)
	}
	if len(matches) == 0 {
		return "", fmt.Errorf("finding regex-syntax %s: no folder matches %s", version, pattern)
	}
	slices.Sort(matches)
	return matches[0], nil
}

// cargoVersion finds the version of the package in a Cargo.toml.
var cargoVersion = regexp.MustCompile(`(?m)^version = "([^"]+)"$`)

// checkCrateVersion makes sure that the crate that holds the folder src has the
// version that the Go files will name. Cargo.toml is two folders above src.
func checkCrateVersion(src, version string) error {
	toml := filepath.Join(src, "..", "..", "Cargo.toml")
	b, err := os.ReadFile(toml)
	if err != nil {
		return fmt.Errorf("reading the version of the crate: %w", err)
	}
	pkg := string(b)
	i := strings.Index(pkg, "[package]\n")
	if i < 0 {
		return fmt.Errorf("reading %s: no [package] section", toml)
	}
	pkg = pkg[i:]
	if j := strings.Index(pkg[1:], "\n["); j >= 0 {
		pkg = pkg[:j+1]
	}
	if !strings.Contains(pkg, "\nname = \"regex-syntax\"\n") {
		return fmt.Errorf("reading %s: the crate is not regex-syntax", toml)
	}
	m := cargoVersion.FindStringSubmatch(pkg)
	if m == nil {
		return fmt.Errorf("reading %s: no version in the [package] section", toml)
	}
	if m[1] != version {
		return fmt.Errorf("reading %s: the crate is at version %s, not %s", toml, m[1], version)
	}
	return nil
}

// convert reads the table files in src and writes the Go files in out. It
// removes a Go file in out that it wrote before and that no table file makes
// now.
func convert(w io.Writer, src, out, version string) error {
	files, err := convertFiles(src, version)
	if err != nil {
		return err
	}
	lic, err := os.ReadFile(filepath.Join(src, licenseFile))
	if err != nil {
		return fmt.Errorf("reading the license of the tables: %w", err)
	}
	files[licenseFile] = lic
	if err := os.MkdirAll(out, 0o755); err != nil {
		return fmt.Errorf("making the folder for the Go files: %w", err)
	}
	if err := removeStale(w, out, files); err != nil {
		return err
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	slices.Sort(names)
	for _, n := range names {
		path := filepath.Join(out, n)
		if err := os.WriteFile(path, files[n], 0o644); err != nil {
			return fmt.Errorf("writing the Go file: %w", err)
		}
		_, _ = fmt.Fprintf(w, "wrote %s, %d bytes\n", path, len(files[n]))
	}
	return nil
}

// convertFiles converts each table file that mod.rs in src names, and returns
// the Go files by name. It fails when src holds a Rust file that mod.rs does
// not name, or when two files name other Unicode versions.
func convertFiles(src, version string) (map[string][]byte, error) {
	mod, err := os.ReadFile(filepath.Join(src, "mod.rs"))
	if err != nil {
		return nil, fmt.Errorf("reading the list of tables: %w", err)
	}
	mods, err := parseModules(string(mod))
	if err != nil {
		return nil, fmt.Errorf("mod.rs: %w", err)
	}
	onDisk, err := filepath.Glob(filepath.Join(src, "*.rs"))
	if err != nil {
		return nil, fmt.Errorf("listing the table files: %w", err)
	}
	for _, p := range onDisk {
		base := strings.TrimSuffix(filepath.Base(p), ".rs")
		if base != "mod" && !slices.Contains(mods, base) {
			return nil, fmt.Errorf("reading %s, which mod.rs does not name", p)
		}
	}
	files := map[string][]byte{}
	names := map[string]string{}
	unicode := ""
	for _, base := range mods {
		b, err := os.ReadFile(filepath.Join(src, base+".rs"))
		if err != nil {
			return nil, fmt.Errorf("reading a table file: %w", err)
		}
		f, err := parseFile(string(b))
		if err != nil {
			return nil, fmt.Errorf("%s.rs: %w", base, err)
		}
		switch {
		case unicode == "":
			unicode = f.unicode
		case unicode != f.unicode:
			return nil, fmt.Errorf("%s.rs: reading Unicode %s, where the other files are at Unicode %s", base, f.unicode, unicode)
		}
		g, err := emit(base, version, f, names)
		if err != nil {
			return nil, err
		}
		if _, ok := files[base+".go"]; ok {
			return nil, fmt.Errorf("mod.rs: naming %s twice", base)
		}
		files[base+".go"] = g
	}
	return files, nil
}

// removeStale removes each Go file in out that the command wrote and that is
// not in files.
func removeStale(w io.Writer, out string, files map[string][]byte) error {
	entries, err := os.ReadDir(out)
	if err != nil {
		return fmt.Errorf("listing the Go files: %w", err)
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || files[e.Name()] != nil {
			continue
		}
		path := filepath.Join(out, e.Name())
		gen, err := isGenerated(path)
		if err != nil {
			return err
		}
		if !gen {
			continue
		}
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("removing a Go file that no table makes now: %w", err)
		}
		_, _ = fmt.Fprintf(w, "removed %s\n", path)
	}
	return nil
}

// isGenerated reports whether the Go file at path starts with the line that
// the command writes.
func isGenerated(path string) (bool, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return false, fmt.Errorf("reading a Go file: %w", err)
	}
	return bytes.HasPrefix(b, []byte(generatedPrefix)), nil
}

// repoRoot returns the root of the transit repository, which holds the test
// module in test/.
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("finding the working folder: %w", err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "test", "go.mod")); err == nil {
			if _, err := os.Stat(filepath.Join(dir, "docs", "UPSTREAM.md")); err == nil {
				return dir, nil
			}
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("finding the root of the transit repository from %s: %w", dir, fs.ErrNotExist)
		}
		dir = parent
	}
}
